    /**
     * The names of the boolean flags this {@code GLCapabilities} has set.
     *
     * <p>Reflective on purpose; see the constructor. Only public instance {@code boolean} fields are considered, so
     * the function-pointer fields ({@code glEnable}, ...) and any static constants are skipped.</p>
     */
    private static Set<String> enabledFlags(GLCapabilities capabilities) {
        Set<String> on = new java.util.HashSet<>();
        for (java.lang.reflect.Field field : GLCapabilities.class.getFields()) {
            if (field.getType() != boolean.class || java.lang.reflect.Modifier.isStatic(field.getModifiers())) {
                continue;
            }
            try {
                if (field.getBoolean(capabilities)) {
                    on.add(field.getName());
                }
            } catch (IllegalAccessException e) {
                // Public field on a public class: reachable unless a security manager says otherwise, and the game
                // has none. Wrapping keeps the compiler's checked exception out of every caller.
                throw new IllegalStateException("cannot read " + field.getName(), e);
            }
        }
        return on;
    }

