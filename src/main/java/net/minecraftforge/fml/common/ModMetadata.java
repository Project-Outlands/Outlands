package net.minecraftforge.fml.common;

import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

import net.minecraftforge.fml.common.versioning.ArtifactVersion;

import com.google.common.base.Joiner;
import com.google.common.collect.Lists;
import com.google.common.collect.Sets;
import com.google.gson.annotations.SerializedName;

/**
 * @author cpw
 *
 */
public class ModMetadata
{
    @SerializedName("modid")
    public String modId;
    public String name;
    public String description = "";

    public String url = "";
    @Deprecated //Never really used for anything and format is undefined. See updateJSON for replacement.
    public String updateUrl = "";
    /**
     * URL to update json file. Format is defined here: https://gist.github.com/LexManos/7aacb9aa991330523884
     */
    public String updateJSON = "";
    public String logoFile = "";
    public String version = "";
    public List<String> authorList = Lists.newArrayList();
    public String credits = "";
    public String parent = "";
    public String[] screenshots;

    /**
     * The language the mod's entry class is written in, mirroring {@code @Mod#modLanguage()}. Declaring it in both
     * places is fine as long as the values agree; disagreeing values are rejected rather than resolved.
     */
    public String modLanguage = "";
    /**
     * The full class name of an {@link ILanguageAdapter} to construct this mod with, mirroring
     * {@code @Mod#modLanguageAdapter()}. Takes precedence over {@link #modLanguage} when set.
     */
    public String modLanguageAdapter = "";
    /**
     * A version constraint on the language runtime, for languages whose provider can state which versions it supports.
     * Recorded but not enforced while nothing declares supported versions.
     */
    public String modLanguageVersion = "";

    // this field is not for use in the json
    public transient ModContainer parentMod;
    // this field is not for use in the json
    public transient List<ModContainer> childMods = Lists.newArrayList();

    /**
     * Whether this entry's dependency lists are the ones to use.
     *
     * <p>Only meaningful for metadata written before the {@code jar} section existed: back then the entry duplicated
     * the annotation, so a jar had to say which of the two it meant. A jar that declares the section is read directly
     * and this flag does nothing - keeping it in the new format would be a second switch for a question the section
     * already answered.
     *
     * @deprecated declare the {@code jar} section instead, which makes the entry authoritative on its own
     */
    @Deprecated
    public boolean useDependencyInformation;
    /**
     * The dependencies this entry declares with {@code depends}, as written.
     *
     * <p>Transient because the three lists below are what the sorter reads: this is the declaration, those are its
     * settled form for one launch. Kept apart so the side filter can be applied where the side is known, and so a
     * container can answer "what did this mod declare" without undoing a filter.
     */
    public transient List<ModDependency> declaredDependencies = List.of();
    public Set<ArtifactVersion> requiredMods = Sets.newHashSet();
    public List<ArtifactVersion> dependencies = Lists.newArrayList();
    public List<ArtifactVersion> dependants = Lists.newArrayList();
    /**
     * Use for extra data, should write it like
     *   "modProperties": {
     *       "keyA": "valueA",
     *       "keyB": "valueB"
     *   }
     */
    public Map<String, String> modProperties = HashMap.newHashMap(5);
    // this field is not for use in the json
    public transient boolean autogenerated;

    public ModMetadata()
    {
    }

    /**
     * Fills the three lists from {@link #declaredDependencies}, dropping the dependencies scoped to the other side.
     *
     * <p>Rebuilt from the declaration every time, so calling it twice is the same as calling it once - the container
     * side and the declarative side of the loader both have a reason to ask.
     */
    public void resolveDeclaredDependencies(net.minecraftforge.fml.relauncher.Side launchSide)
    {
        if (declaredDependencies.isEmpty())
        {
            return;
        }
        net.minecraftforge.fml.common.versioning.DependencyParser.DependencyInfo info =
                new net.minecraftforge.fml.common.versioning.DependencyParser.DependencyInfo();
        for (ModDependency dependency : declaredDependencies)
        {
            dependency.applyTo(info, launchSide);
        }
        requiredMods = info.requirements;
        dependencies = info.dependencies;
        dependants = info.dependants;
    }

    /**
     * @return whether this entry says anything about dependencies at all, in either form
     */
    public boolean declaresDependencies()
    {
        return !declaredDependencies.isEmpty()
                || requiredMods != null && !requiredMods.isEmpty()
                || dependencies != null && !dependencies.isEmpty()
                || dependants != null && !dependants.isEmpty();
    }

    public String getChildModCountString()
    {
        return String.format("%d child mod%s", childMods.size(), childMods.size() != 1 ? "s" : "");
    }

    public String getAuthorList()
    {
        return Joiner.on(", ").join(authorList);
    }

    public String getChildModList()
    {
        return Joiner.on(", ").join(childMods.stream().map(ModContainer::getName).iterator());
    }

    public String printableSortingRules()
    {
        return "";
    }
}
